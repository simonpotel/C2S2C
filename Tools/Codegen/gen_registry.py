#!/usr/bin/env python3
"""Generates the packet tables for every language from Registry/protocol.toml.

Usage: gen_registry.py            write Generated/* (and extend Registry/ids.lock)
       gen_registry.py --check    write nothing; exit 1 if Generated/* is stale or invalid
Needs Python 3.11+ (tomllib), no other dependency.

Why one generator: the packet ids and layouts must be identical in C, C++, Python, Rust and
TypeScript. Writing them by hand five times guarantees they drift; generating them makes the
TOML file the single source of truth.
"""
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
BASE = ["u8", "u16", "u32", "u64", "i8", "i16", "i32", "i64", "f32", "f64", "bool", "string", "bytes"]
BANNER = "GENERATED by Tools/Codegen/gen_registry.py from Registry/protocol.toml - DO NOT EDIT."


def load():
    """Reads and validates the registry; returns the packets sorted by id."""
    data = tomllib.loads((ROOT / "Registry/protocol.toml").read_text())
    packets, names, ids = [], set(), set()
    for p in data["packet"]:
        name, pid = p["name"], p["id"]
        if not re.fullmatch(r"[a-z][a-z0-9_]*", name) or name in names:
            sys.exit(f"bad or duplicate packet name: {name}")
        if not 0 < pid < 0x10000 or pid in ids:
            sys.exit(f"bad or duplicate id: {name} 0x{pid:04X}")
        if 0x7F00 <= pid <= 0x7FFF or 0xFF00 <= pid <= 0xFFFF:
            sys.exit(f"{name}: id 0x{pid:04X} is in a range reserved for the library")
        fields = []
        for f in p.get("fields", []):
            fname, ftype = f.split(":")
            elem = ftype[6:-1] if ftype.startswith("array<") else None
            if (elem or ftype) not in BASE or fname in [x[0] for x in fields]:
                sys.exit(f"{name}: bad or duplicate field {f}")
            fields.append((fname, ftype))
        names.add(name)
        ids.add(pid)
        packets.append({"name": name, "id": pid, "deprecated": p.get("deprecated", False),
                        "fields": fields})
    return sorted(packets, key=lambda p: p["id"])


def schema_text(p):
    """'u32,string,array<u16>' - the same notation the test vectors use."""
    return ",".join(t for _, t in p["fields"])


def c_field(t):
    return f"{{C2S2C_T_ARRAY, C2S2C_T_{t[6:-1].upper()}}}" if t.startswith("array<") else f"{{C2S2C_T_{t.upper()}, 0}}"


def gen_c_header(ps):
    ids = "\n".join(f"#define C2S2C_PKT_{p['name'].upper()} 0x{p['id']:04X}u" for p in ps)
    return f"""/* {BANNER} */
#ifndef C2S2C_PACKETS_H
#define C2S2C_PACKETS_H

#include "C2S2C/c2s2c_types.h"

/* Packet ids (bit 15 set = server to client). */
{ids}

/** One registry entry; the table c2s2c_registry is sorted by id. */
typedef struct c2s2c_packet_info {{
    uint16_t id;
    const char* name;
    int deprecated; /* 1 = retired id: still valid, do not use in new code */
    c2s2c_schema schema;
}} c2s2c_packet_info;

extern const c2s2c_packet_info c2s2c_registry[];
extern const unsigned c2s2c_registry_count;

#endif
"""


def gen_c_source(ps):
    arrays, rows = [], []
    for p in ps:
        n = p["name"]
        if p["fields"]:
            arrays.append(f"static const c2s2c_field c2s2c_f_{n}[] = {{{', '.join(c_field(t) for _, t in p['fields'])}}};")
        fields = f"c2s2c_f_{n}" if p["fields"] else "NULL"
        rows.append(f"    {{0x{p['id']:04X}u, \"{n}\", {int(p['deprecated'])}, {{{len(p['fields'])}, {fields}}}}},")
    return f"""/* {BANNER} */
#include "c2s2c_packets.h"

{chr(10).join(arrays)}

const c2s2c_packet_info c2s2c_registry[] = {{
{chr(10).join(rows)}
}};
const unsigned c2s2c_registry_count = {len(ps)};
"""


def gen_cpp(ps):
    consts = "\n".join(f"constexpr uint16_t {p['name'].upper()} = 0x{p['id']:04X};" for p in ps)
    rows = "\n".join(f'    {{{p["name"].upper()}, "{p["name"]}", "{schema_text(p)}"}},' for p in ps)
    return f"""// {BANNER}
#pragma once
#include <cstdint>

namespace c2s2c::pkt {{
{consts}

struct Info {{ uint16_t id; const char* name; const char* schema; }};
inline constexpr Info all[] = {{
{rows}
}};
}}  // namespace c2s2c::pkt
"""


def gen_py(ps):
    consts = "\n".join(f"{p['name'].upper()} = 0x{p['id']:04X}" for p in ps)
    rows = "\n".join(f'    {p["name"].upper()}: ("{p["name"]}", "{schema_text(p)}"),' for p in ps)
    return f'''# {BANNER}
{consts}

# id -> (name, schema)
PACKETS = {{
{rows}
}}
'''


def gen_rust(ps):
    consts = "\n".join(f"pub const {p['name'].upper()}: u16 = 0x{p['id']:04X};" for p in ps)
    rows = "\n".join(f'    ({p["name"].upper()}, "{p["name"]}", "{schema_text(p)}"),' for p in ps)
    return f"""// {BANNER}
{consts}

/// (id, name, schema)
pub const PACKETS: &[(u16, &str, &str)] = &[
{rows}
];
"""


def gen_ts(ps):
    consts = "\n".join(f"export const {p['name'].upper()} = 0x{p['id']:04X};" for p in ps)
    rows = "\n".join(f'  [{p["name"].upper()}, {{ name: "{p["name"]}", schema: "{schema_text(p)}" }}],' for p in ps)
    return f"""// {BANNER}
{consts}

export const PACKETS = new Map<number, {{ name: string; schema: string }}>([
{rows}
]);
"""


def gen_golden(ps):
    """Language-neutral listing: every language test compares its own tables against this."""
    return "".join(f"0x{p['id']:04X} {p['name']} {schema_text(p)}\n" for p in ps)


# One folder per target language, plus the neutral listing used by the tests.
OUTPUTS = {
    "Generated/C/c2s2c_packets.h": gen_c_header,
    "Generated/C/c2s2c_registry.c": gen_c_source,
    "Generated/Cpp/c2s2c_packets.hpp": gen_cpp,
    "Generated/Python/c2s2c_registry.py": gen_py,
    "Generated/Rust/registry.rs": gen_rust,
    "Generated/TypeScript/registry.ts": gen_ts,
    "Generated/registry.txt": gen_golden,
}


def check_lock(ps, write):
    """ids.lock remembers every id ever used: deleting or renaming one is refused."""
    lock = ROOT / "Registry/ids.lock"
    known = dict(line.split()[::-1] for line in lock.read_text().split("\n") if line) if lock.exists() else {}
    by_name = {p["name"]: p for p in ps}
    for name, hex_id in known.items():
        if name not in by_name or by_name[name]["id"] != int(hex_id, 16):
            sys.exit(f"id {hex_id} ({name}) was removed or changed: ids are never reused, use deprecated = true")
    new = {p["name"]: f"0x{p['id']:04X}" for p in ps}
    if write and new != known:
        lock.write_text("".join(f"{i} {n}\n" for n, i in sorted(new.items(), key=lambda x: x[1])))
    return new == known or write


def main():
    check = "--check" in sys.argv
    ps = load()
    stale = [] if check_lock(ps, not check) else ["Registry/ids.lock"]
    for path, gen in OUTPUTS.items():
        text, file = gen(ps), ROOT / path
        if check:
            if not file.exists() or file.read_text() != text:
                stale.append(path)
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(text)
    if stale:
        print("stale (run Tools/Codegen/gen_registry.py):", *stale)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
